/* ══════════════════════════════════════════════════════════════════════
   Schema → TypeScript (DEC-170 mitigation 1). Types are DERIVED from the
   live database schema, never hand-maintained beside it. CI regenerates
   and fails if the committed file differs, so schema and types cannot
   drift. Run with `pnpm db:types` (needs DATABASE_URL).

   Maps every user table/column to a TypeScript row type. pgmigrations
   (the migration tool's bookkeeping) and system schemas are excluded.
   ══════════════════════════════════════════════════════════════════════ */
import { Client } from 'pg';

const OUT = new URL('../packages/shared-types/src/db.generated.ts', import.meta.url).pathname;

const PG_TO_TS = {
  // information_schema reports the internal names (int4, int8, bool, …)
  int2: 'number', int4: 'number', int8: 'string',
  smallint: 'number', integer: 'number', bigint: 'string',
  float4: 'number', float8: 'number', real: 'number', 'double precision': 'number',
  numeric: 'string', money: 'string',
  text: 'string', varchar: 'string', bpchar: 'string', char: 'string', name: 'string',
  uuid: 'string', bool: 'boolean', boolean: 'boolean', date: 'string',
  timestamp: 'Date', 'timestamp without time zone': 'Date',
  'timestamp with time zone': 'Date', timestamptz: 'Date',
  time: 'string', interval: 'string', json: 'unknown', jsonb: 'unknown',
  bytea: 'Buffer',
};

function tsFor(udtName) {
  if (PG_TO_TS[udtName]) return PG_TO_TS[udtName];
  if (udtName === 'geometry' || udtName === 'geography') return 'unknown'; // PostGIS
  return 'unknown';
}

const client = new Client({ connectionString: process.env.DATABASE_URL });
await client.connect();

const { rows } = await client.query(`
  SELECT c.table_name, c.column_name, c.udt_name, c.is_nullable, c.ordinal_position
  FROM information_schema.columns c
  JOIN information_schema.tables t
    ON t.table_schema = c.table_schema AND t.table_name = c.table_name
  WHERE c.table_schema = 'public'
    AND c.table_name <> 'pgmigrations'          -- the migration tool's bookkeeping
    AND t.table_type = 'BASE TABLE'             -- skip views (geometry_columns & co)
    AND NOT EXISTS (                            -- skip tables owned by an extension
      SELECT 1 FROM pg_depend d
      JOIN pg_class cls ON cls.oid = d.objid
      JOIN pg_namespace ns ON ns.oid = cls.relnamespace
      JOIN pg_extension e ON e.oid = d.refobjid
      WHERE cls.relname = c.table_name AND ns.nspname = 'public'
    )
  ORDER BY c.table_name, c.ordinal_position`);

const tables = {};
for (const r of rows) {
  (tables[r.table_name] ??= {})[r.column_name] = {
    type: tsFor(r.udt_name),
    nullable: r.is_nullable === 'YES',
    pg: r.udt_name,
  };
}

const tableNames = Object.keys(tables).sort();
const lines = [];
lines.push('/* AUTO-GENERATED by scripts/gen-db-types.mjs — DO NOT EDIT BY HAND.');
lines.push(' * Regenerate with `pnpm db:types`. CI regenerates and fails if this differs. */');
lines.push('');
lines.push(`export const DB_SCHEMA_VERSION = ${JSON.stringify(JSON.stringify(tableNames))};`);
lines.push('');
lines.push('export type DbColumn = { type: string; nullable: boolean; pg: string };');
lines.push('');
lines.push('export type DbSchema = {');
if (tableNames.length === 0) {
  lines.push('  // No domain tables yet (P0.5: migration 0001 enables PostGIS only).');
}
for (const t of tableNames) {
  lines.push(`  ${t}: {`);
  for (const [col, meta] of Object.entries(tables[t])) {
    lines.push(`    ${col}: ${JSON.stringify(meta)},`);
  }
  lines.push('  };');
}
lines.push('};');
lines.push('');
lines.push('export const dbSchema = {} as DbSchema;');
lines.push('');
await client.end();

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`generated ${tableNames.length} table(s) → packages/shared-types/src/db.generated.ts`);
