#!/usr/bin/env node
/* The native splash paints before the WebView does, and the generated Android project has ONE
   drawable for both themes — so a dark-mode cold start flashed white, then went dark. That cannot
   be fixed from the web layer: it is a binary concern, and the fix belongs in `values-night`.

   `cap add android` is run by CI (the tree is generated, never committed), so this writes the night
   resources after the platform is added. The colour comes from packages/brand/brand.json — the same
   palette the web stylesheet and the boot page are held to — because a second copy of a hex value is
   how the boot page ended up a grey step out of step with the app it launches.

   It fails loudly rather than quietly doing nothing: if the day theme does not carry the anchor this
   script mirrors, the night resources would be dead files in a binary nobody can inspect. */
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..", "..", "..");
const BRAND = JSON.parse(fs.readFileSync(path.join(ROOT, "packages", "brand", "brand.json"), "utf8"));
const dark = BRAND.palette && BRAND.palette.dark;
if (!dark || !dark.paper) throw new Error("brand.json has no palette.dark.paper to paint the night splash with");

const res = path.join(ROOT, "apps", "mobile", "android", "app", "src", "main", "res");
const day = path.join(res, "values", "styles.xml");
if (!fs.existsSync(day)) {
  throw new Error(`no generated Android theme at ${path.relative(ROOT, day)} — run it after \`npx cap add android\``);
}
const dayText = fs.readFileSync(day, "utf8");
if (!/name="AppTheme\.NoActionBarLaunch"/.test(dayText)) {
  throw new Error("values/styles.xml does not declare AppTheme.NoActionBarLaunch; the template changed and this script must be re-read against it");
}
/* `@drawable/splash` is what the day theme paints. The night theme re-declares the same style with a
   colour instead, and also sets the API-31 splash colour so the system splash window agrees with the
   WebView that follows it rather than with a picture made for daylight. */
const dir = path.join(res, "values-night");
fs.mkdirSync(dir, { recursive: true });
const files = {
  "colors.xml": `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Generated by scripts/apply-android-night-splash.js from packages/brand/brand.json. Do not
         hand-edit: change the palette there and rebuild the installer. -->
    <color name="rs_splash_background">${dark.paper}</color>
    <color name="rs_splash_bar">#00000000</color>
</resources>
`,
  "styles.xml": `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Generated by scripts/apply-android-night-splash.js. The day theme keeps the template's
         @drawable/splash; this is the dark counterpart, so a dark-mode cold start opens on the
         brand's ink paper instead of flashing white. -->
    <style name="AppTheme.NoActionBarLaunch" parent="Theme.SplashScreen">
        <item name="android:background">@color/rs_splash_background</item>
        <item name="android:windowSplashScreenBackground">@color/rs_splash_background</item>
        <item name="android:windowLightStatusBar">false</item>
    </style>
    <style name="AppTheme.NoActionBar" parent="Theme.AppCompat.DayNight.NoActionBar">
        <item name="windowActionBar">false</item>
        <item name="windowNoTitle">true</item>
        <item name="android:background">@null</item>
    </style>
</resources>
`,
};
/* Lint holds the line here, and it is right: `lintVitalRelease` fails the build with
   MissingDefaultResource when a `values-night` resource has no base declaration. The debug variant
   never ran that lint task, so this sat latent until D-8.18 made both variants share one prep —
   which is the argument for the shared prep, not against it. Every colour this script introduces
   is therefore declared in BOTH folders: the day value is the brand's light paper, so anything that
   queries it outside a night configuration gets a colour that belongs to this app rather than a
   default that does not. */
const light = (BRAND.palette && BRAND.palette.light) || {};
if (!light.paper) throw new Error("brand.json has no palette.light.paper to declare beside the night colours");
const baseColors = { rs_splash_background: light.paper, rs_splash_bar: "#00000000" };
const baseDir = path.join(res, "values");
const basePath = path.join(baseDir, "colors.xml");
let baseText = fs.existsSync(basePath) ? fs.readFileSync(basePath, "utf8") : null;
if (baseText === null) {
  baseText = `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n${Object.entries(baseColors)
    .map(([n, v]) => `    <color name="${n}">${v}</color>`).join("\n")}\n</resources>\n`;
} else {
  const missing = Object.entries(baseColors).filter(([n]) => !new RegExp(`name="${n}"`).test(baseText));
  if (missing.length) {
    const add = missing.map(([n, v]) => `    <color name="${n}">${v}</color>`).join("\n");
    if (!/<\/resources>/.test(baseText)) throw new Error(`${basePath} has no </resources> to insert the night-pair colours into`);
    baseText = baseText.replace(/<\/resources>/, `${add}\n</resources>`);
  }
}
const baseNow = fs.existsSync(basePath) ? fs.readFileSync(basePath, "utf8") : null;
if (baseNow !== baseText) fs.writeFileSync(basePath, baseText);

const written = [];
for (const [name, body] of Object.entries(files)) {
  const p = path.join(dir, name);
  if (fs.existsSync(p) && fs.readFileSync(p, "utf8") === body) continue;
  fs.writeFileSync(p, body);
  written.push(path.relative(ROOT, p));
}
const baseNote = " + values/colors.xml (base declarations, lint requires them for anything in values-night)";
console.log(written.length ? `night splash resources: ${written.join(", ")}${baseNote}` : "night splash resources already current");
